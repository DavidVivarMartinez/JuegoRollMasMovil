-- Contenido de la partida: misiones, inventario, archivos, mapa y cuenta atrás

ALTER TABLE game_session ADD COLUMN countdown_label VARCHAR(120);
ALTER TABLE game_session ADD COLUMN countdown_ends_at TIMESTAMP WITH TIME ZONE;

-- player_id NULL = misión de toda la tripulación
CREATE TABLE mission (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   UUID NOT NULL REFERENCES game_session (id),
    player_id    UUID REFERENCES player (id),
    code         VARCHAR(40),
    kind         VARCHAR(10) NOT NULL,
    title        VARCHAR(120) NOT NULL,
    description  VARCHAR(2000),
    status       VARCHAR(10) NOT NULL,
    sort_order   INTEGER NOT NULL DEFAULT 0,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_mission_session ON mission (session_id, player_id);

CREATE TABLE inventory_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   UUID NOT NULL REFERENCES game_session (id),
    player_id    UUID NOT NULL REFERENCES player (id),
    name         VARCHAR(80) NOT NULL,
    description  VARCHAR(500),
    quantity     INTEGER NOT NULL DEFAULT 1,
    usable       BOOLEAN NOT NULL DEFAULT TRUE,
    consumable   BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_item_player ON inventory_item (player_id);

-- player_id NULL = archivo visible para toda la tripulación (cuando está desbloqueado)
CREATE TABLE game_file (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      UUID NOT NULL REFERENCES game_session (id),
    player_id       UUID REFERENCES player (id),
    code            VARCHAR(40),
    title           VARCHAR(120) NOT NULL,
    classification  VARCHAR(12) NOT NULL,
    body            VARCHAR(8000),
    status          VARCHAR(10) NOT NULL,
    sort_order      INTEGER NOT NULL DEFAULT 0,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_file_session ON game_file (session_id, player_id);

CREATE TABLE map_sector (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  UUID NOT NULL REFERENCES game_session (id),
    code        VARCHAR(30) NOT NULL,
    name        VARCHAR(80) NOT NULL,
    status      VARCHAR(12) NOT NULL,
    note        VARCHAR(500),
    x           INTEGER NOT NULL DEFAULT 0,
    y           INTEGER NOT NULL DEFAULT 0,
    links       VARCHAR(200),
    sort_order  INTEGER NOT NULL DEFAULT 0,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_map_sector UNIQUE (session_id, code)
);
