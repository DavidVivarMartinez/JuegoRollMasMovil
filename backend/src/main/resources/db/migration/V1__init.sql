-- PROTOCOLO: ECLIPSE — esquema inicial (compatible con PostgreSQL y H2 en modo PostgreSQL)

CREATE TABLE game_session (
    id          UUID PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    started_at  TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Incluye al máster (role = MASTER) y a los cuatro jugadores (role = PLAYER)
CREATE TABLE player (
    id               UUID PRIMARY KEY,
    session_id       UUID NOT NULL REFERENCES game_session (id),
    role             VARCHAR(10) NOT NULL,
    name             VARCHAR(80) NOT NULL,
    character_name   VARCHAR(80),
    character_code   VARCHAR(30),
    access_code_hash VARCHAR(64) NOT NULL UNIQUE,
    token_hash       VARCHAR(64) UNIQUE,
    token_issued_at  TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_player_session ON player (session_id);

CREATE TABLE message (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    UUID NOT NULL REFERENCES game_session (id),
    recipient_id  UUID REFERENCES player (id),      -- NULL = mensaje global
    sender_label  VARCHAR(80) NOT NULL,
    text          VARCHAR(2000) NOT NULL,
    type          VARCHAR(20) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at       TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_message_session_created ON message (session_id, created_at);
CREATE INDEX ix_message_recipient ON message (recipient_id);

CREATE TABLE player_state (
    player_id     UUID PRIMARY KEY REFERENCES player (id),
    health        INTEGER NOT NULL DEFAULT 100,
    infection     INTEGER NOT NULL DEFAULT 0,
    private_vars  VARCHAR(4000) NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE module_state (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  UUID NOT NULL REFERENCES game_session (id),
    player_id   UUID NOT NULL REFERENCES player (id),
    module      VARCHAR(30) NOT NULL,
    locked      BOOLEAN NOT NULL DEFAULT FALSE,
    visible     BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_module_state UNIQUE (player_id, module)
);

CREATE TABLE player_action (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  UUID NOT NULL REFERENCES game_session (id),
    player_id   UUID NOT NULL REFERENCES player (id),
    module      VARCHAR(30),
    type        VARCHAR(40) NOT NULL,
    payload     VARCHAR(4000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_player_action_session ON player_action (session_id, created_at);

CREATE TABLE audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   UUID NOT NULL REFERENCES game_session (id),
    actor_id     UUID,
    actor_label  VARCHAR(80) NOT NULL,
    action       VARCHAR(60) NOT NULL,
    target       VARCHAR(200),
    details      VARCHAR(2000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_audit_session ON audit_log (session_id, created_at);
