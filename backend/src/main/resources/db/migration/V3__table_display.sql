-- Pantalla de mesa (TV): estado que controla el máster y mapas subidos como imagen

-- Estado completo de la pantalla en JSON (escena actual, fichas, niebla, efectos). Una fila por partida.
CREATE TABLE display_state (
    session_id  UUID PRIMARY KEY REFERENCES game_session (id),
    state_json  VARCHAR(200000) NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Mapas subidos por el máster. La imagen se guarda en la propia base de datos (ya redimensionada en el móvil).
CREATE TABLE map_image (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    UUID NOT NULL REFERENCES game_session (id),
    name          VARCHAR(80) NOT NULL,
    content_type  VARCHAR(40) NOT NULL,
    width         INTEGER NOT NULL,
    height        INTEGER NOT NULL,
    size_bytes    INTEGER NOT NULL,
    data          BYTEA NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_map_image_session ON map_image (session_id);
